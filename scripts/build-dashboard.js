#!/usr/bin/env node
"use strict";
/**
 * Generates webapp/dashboard/ — a plain-web copy of the extension's new-tab
 * dashboard, served at nestpane.kneeraazon.com/dashboard/ so people can try
 * Nestpane without installing anything.
 *
 * This is a BUILD OUTPUT, not hand-duplicated code: app.js, every lib/*.js
 * module, style.css, fouc.js, and the icon set are the single source of
 * truth in extension/ — this script only copies (and minifies) them.
 * oauth-callback.html is the one file that's genuinely web-only and lives
 * directly in webapp/dashboard/ instead, since it has no extension
 * equivalent to generate from.
 *
 * Re-run this (`node scripts/build-dashboard.js`) any time extension/
 * changes and the dashboard needs to catch up — it is NOT run automatically
 * by anything yet.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const EXT = path.join(ROOT, "extension");
const OUT = path.join(ROOT, "webapp", "dashboard");
const esbuild = require(path.join(EXT, "node_modules", "esbuild"));

const JS_FILES = ["app.js", "fouc.js"];
const LIB_FILES = ["format.js", "migrations.js", "drive-conflict.js", "autosave.js", "bookmarks-store.js"];
const ICON_FILES = ["favicon.png", "favicon.svg", "icon-16.png", "icon-48.png"];

async function minifyJs(srcPath) {
  const result = await esbuild.transform(fs.readFileSync(srcPath, "utf8"), {
    minify: true,
    target: "es2020",
    loader: "js"
  });
  return result.code;
}

async function minifyCss(srcPath) {
  const result = await esbuild.transform(fs.readFileSync(srcPath, "utf8"), {
    minify: true,
    loader: "css"
  });
  return result.code;
}

function buildIndexHtml() {
  let html = fs.readFileSync(path.join(EXT, "newtab.html"), "utf8");
  // Head-only patch: the extension's newtab.html has no SEO metadata
  // (it's never rendered as a "page" with a URL) — the web dashboard is a
  // real, indexable URL, so it gets one. Nothing in <body> is touched.
  html = html.replace(
    "<title>Nestpane</title>",
    [
      "<title>Nestpane Dashboard — try it in your browser</title>",
      '  <meta name="description" content="The Nestpane dashboard, running in your browser — no extension install needed. Bookmarks, notes, tasks, focus timer, habits, and journal, saved locally.">',
      '  <link rel="canonical" href="https://nestpane.kneeraazon.com/dashboard/">',
      '  <meta name="robots" content="index, follow">'
    ].join("\n")
  );
  return html;
}

async function build() {
  fs.mkdirSync(path.join(OUT, "lib"), { recursive: true });
  fs.mkdirSync(path.join(OUT, "icons"), { recursive: true });

  for (const file of JS_FILES) {
    const code = await minifyJs(path.join(EXT, file));
    fs.writeFileSync(path.join(OUT, file), code);
    console.log("  ✓", file);
  }
  for (const file of LIB_FILES) {
    const code = await minifyJs(path.join(EXT, "lib", file));
    fs.writeFileSync(path.join(OUT, "lib", file), code);
    console.log("  ✓ lib/" + file);
  }
  const css = await minifyCss(path.join(EXT, "style.css"));
  fs.writeFileSync(path.join(OUT, "style.css"), css);
  console.log("  ✓ style.css");

  for (const file of ICON_FILES) {
    fs.copyFileSync(path.join(EXT, "icons", file), path.join(OUT, "icons", file));
    console.log("  ✓ icons/" + file);
  }

  fs.writeFileSync(path.join(OUT, "index.html"), buildIndexHtml());
  console.log("  ✓ index.html (generated from extension/newtab.html)");

  if (!fs.existsSync(path.join(OUT, "oauth-callback.html"))) {
    console.warn("  ⚠ oauth-callback.html is missing from webapp/dashboard/ — Google sign-in on the web dashboard will not work without it. This file is hand-written, not generated by this script.");
  }

  console.log("\n✓ Dashboard build complete — webapp/dashboard/ is ready to deploy.");
}

build().catch((err) => {
  console.error("Dashboard build failed:", err);
  process.exit(1);
});
